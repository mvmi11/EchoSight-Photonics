class EchoSightFusionEngine:
    """
    Central Sensor Fusion Engine for EchoSight.
    Integrates optical centroid detection, linear feature extraction,
    Kalman kinematic prediction, and acoustic FFT analysis.
    """

    def __init__(self, fusion_threshold: float = 0.60):
        self.motion_detector = OpticalMotionDetector(min_area=100)
        self.line_detector = HoughLineDetector(min_line_length=50, max_line_gap=10)
        self.kalman_tracker = KalmanTracker2D(dt=1.0)
        self.acoustic_analyzer = AcousticFFTAnalyzer(sample_rate=44100, target_freq_band=(120.0, 450.0))
        self.fusion_threshold = fusion_threshold

    def process_step(
        self,
        reference_frame: np.ndarray,
        current_frame: np.ndarray,
        audio_chunk: np.ndarray
    ) -> Dict[str, object]:
        """
        Executes one complete multi-sensor perception and tracking cycle.
        """
        # 1. Kinematic Prediction Step
        predicted_pos = self.kalman_tracker.predict()

        # 2. Optical Motion & Centroid Extraction
        centroid, annotated_frame = self.motion_detector.detect_centroid(reference_frame, current_frame)
        optical_score = 1.0 if centroid is not None else 0.0

        # 3. Linear Feature (Filament / Edge) Extraction
        lines, annotated_frame = self.line_detector.detect_lines(annotated_frame)
        linear_score = min(len(lines) / 5.0, 1.0)

        # 4. Kalman State Correction
        if centroid is not None:
            estimated_pos = self.kalman_tracker.update(centroid)
        else:
            estimated_pos = predicted_pos

        # Draw Kalman Predicted Position (Blue Circle) vs Corrected Position (Red Circle)
        cv2.circle(annotated_frame, predicted_pos, 7, (255, 0, 0), 2)
        cv2.putText(
            annotated_frame,
            f"Kalman Est: {estimated_pos}",
            (10, 30),
            cv2.FONT_HERSHEY_SIMPLEX,
            0.6,
            (255, 255, 255),
            2
        )

        # 5. Acoustic Spectral Analysis
        acoustic_data = self.acoustic_analyzer.analyze_signal(audio_chunk)
        acoustic_score = float(acoustic_data["confidence"])

        # 6. Weighted Multi-Sensor Fusion Score
        # Weights: 45% Optical Motion, 40% Acoustic Signature, 15% Linear Features
        fused_confidence = (0.45 * optical_score) + (0.40 * acoustic_score) + (0.15 * linear_score)
        alert_triggered = fused_confidence >= self.fusion_threshold

        return {
            "alert": alert_triggered,
            "fused_confidence": round(fused_confidence, 2),
            "measured_centroid": centroid,
            "kalman_estimate": estimated_pos,
            "detected_lines_count": len(lines),
            "acoustic_freq_hz": acoustic_data["dominant_freq"],
            "annotated_frame": annotated_frame
        }


