class OpticalMotionDetector:
    """
    Optical motion detection module for the EchoSight system.
    Computes frame differencing and extracts target centroid coordinates.
    """

    def __init__(self, min_area: int = 100, blur_kernel: Tuple[int, int] = (5, 5), threshold_val: int = 25):
        self.min_area = min_area
        self.blur_kernel = blur_kernel
        self.threshold_val = threshold_val

    def detect_centroid(self, reference_frame: np.ndarray, current_frame: np.ndarray) -> Tuple[Optional[Tuple[int, int]], np.ndarray]:
        """
        Detects the largest moving object between two frames and returns its (x, y) centroid.
        """
        output_frame = current_frame.copy()

        # 1. Compute absolute difference and convert to grayscale
        frame_diff = cv2.absdiff(reference_frame, current_frame)
        gray_diff = cv2.cvtColor(frame_diff, cv2.COLOR_BGR2GRAY)

        # 2. Apply Gaussian smoothing and binary thresholding
        blurred = cv2.GaussianBlur(gray_diff, self.blur_kernel, 0)
        _, binary_mask = cv2.threshold(blurred, self.threshold_val, 255, cv2.THRESH_BINARY)

        # 3. Extract external contours
        contours, _ = cv2.findContours(binary_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

        largest_contour = None
        max_area = 0.0

        for contour in contours:
            area = cv2.contourArea(contour)
            if area > self.min_area and area > max_area:
                max_area = area
                largest_contour = contour

        if largest_contour is not None:
            x, y, w, h = cv2.boundingRect(largest_contour)
            centroid = (x + w // 2, y + h // 2)

            # Annotate bounding box and centroid on the output frame
            cv2.rectangle(output_frame, (x, y), (x + w, y + h), (0, 255, 0), 2)
            cv2.circle(output_frame, centroid, 5, (0, 0, 255), -1)
            cv2.putText(
                output_frame,
                f"Target: {centroid}",
                (x, max(y - 10, 15)),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.5,
                (0, 255, 0),
                2
            )
            return centroid, output_frame

        return None, output_frame


