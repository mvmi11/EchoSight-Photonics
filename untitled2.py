class OpticalFiberWDMSystem:
    def __init__(self, wavelength_nm=1550, alpha_db_km=0.21, dispersion_ps_nm_km=18.0):
        self.wavelength_nm = wavelength_nm
        self.alpha = alpha_db_km
        self.D = dispersion_ps_nm_km

    def evaluate_fiber_link(self, length_km, wdm_channels=16, bit_rate_gbps=10.0):
        total_loss = (self.alpha * length_km) + 1.2
        rx_power = 3.0 - total_loss
        margin = rx_power - (-28.0)
        dispersion = self.D * length_km * 0.8
        capacity = wdm_channels * bit_rate_gbps
        return {
            "rx_power_dbm": round(rx_power, 2),
            "link_margin_db": round(margin, 2),
            "dispersion_ps": round(dispersion, 2),
            "wdm_capacity_gbps": capacity
        }


class FSOGimbalController:
    def __init__(self, kp=0.08, ki=0.01, kd=0.03, fov_deg=60.0, img_width=480):
        self.kp, self.ki, self.kd = kp, ki, kd
        self.deg_per_px = fov_deg / img_width
        self.prev_error = np.zeros(2, dtype=np.float32)
        self.integral = np.zeros(2, dtype=np.float32)

    def compute_gimbal_angles(self, target_xy, frame_center):
        err_x = float(target_xy - frame_center)
        err_y = float(target_xy - frame_center)
        error_px = np.array([err_x, err_y], dtype=np.float32)

        self.integral += error_px
        derivative = error_px - self.prev_error
        self.prev_error = error_px

        control = (self.kp * error_px) + (self.ki * self.integral) + (self.kd * derivative)
        pan_deg = round(float(control) * self.deg_per_px, 3)
        tilt_deg = round(float(control) * self.deg_per_px, 3)
        return pan_deg, tilt_deg

    def evaluate_fso_link(self, distance_km, tracking_error_px, visibility_km=15.0):
        q = 1.3 if visibility_km > 6.0 else 0.585 * (visibility_km ** (1.0 / 3.0))
        atm_alpha = (3.91 / visibility_km) * ((1550.0 / 550.0) ** (-q))
        atm_loss = atm_alpha * distance_km
        pointing_loss = 0.12 * (tracking_error_px ** 2)
        total_loss = atm_loss + pointing_loss
        efficiency = max(0.0, min(100.0, 100.0 * (10.0 ** (-total_loss / 20.0))))
        return {
            "atm_loss_db": round(atm_loss, 2),
            "pointing_loss_db": round(pointing_loss, 2),
            "fso_efficiency_pct": round(efficiency, 1)
        }


