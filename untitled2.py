class HoughLineDetector:
    """
    Linear feature extraction module using Canny Edge Detection and
    Probabilistic Hough Transform to detect thin filaments (e.g., optical fibers)
    or straight airframe edges.
    """

    def __init__(self, canny_low: int = 50, canny_high: int = 150, min_line_length: int = 50, max_line_gap: int = 10):
        self.canny_low = canny_low
        self.canny_high = canny_high
        self.min_line_length = min_line_length
        self.max_line_gap = max_line_gap

    def detect_lines(self, frame: np.ndarray) -> Tuple[List[Tuple[int, int, int, int]], np.ndarray]:
        """
        Detects thin linear segments in the input frame.
        Returns a list of line coordinates (x1, y1, x2, y2) and the annotated image.
        """
        output_frame = frame.copy()
        gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)

        # 1. Edge extraction via Canny operator
        edges = cv2.Canny(gray, self.canny_low, self.canny_high, apertureSize=3)

        # 2. Probabilistic Hough Transform
        lines = cv2.HoughLinesP(
            edges,
            rho=1,
            theta=np.pi / 180,
            threshold=50,
            minLineLength=self.min_line_length,
            maxLineGap=self.max_line_gap
        )

        detected_segments = []
        if lines is not None:
            for line in lines:
                x1, y1, x2, y2 = line
                detected_segments.append((int(x1), int(y1), int(x2), int(y2)))
                # Draw detected linear feature in Cyan
                cv2.line(output_frame, (x1, y1), (x2, y2), (255, 255, 0), 2)

        return detected_segments, output_frame


