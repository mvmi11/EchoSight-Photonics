        cv2.circle(annotated, est, 10, (0, 255, 0), 2)
        cv2.line(annotated, center, est, (0, 0, 255), 2)

        err_px = float(np.linalg.norm(np.array(est) - np.array(last_pt)))
        pan_deg, tilt_deg = self.fso_ctrl.compute_gimbal_angles(est, center)

        fs = 44100
