class AcousticFFTAnalyzer:
    """
    Acoustic spectral analysis module using Fast Fourier Transform (FFT)
    to isolate rotor/propeller harmonic signatures from ambient noise.
    """

    def __init__(self, sample_rate: int = 44100, target_freq_band: Tuple[float, float] = (120.0, 450.0), energy_threshold: float = 0.25):
        self.sample_rate = sample_rate
        self.min_freq, self.max_freq = target_freq_band
        self.energy_threshold = energy_threshold

    def analyze_signal(self, audio_signal: np.ndarray) -> Dict[str, object]:
        """
        Computes the frequency spectrum of a 1D audio signal and checks
        for dominant harmonics within the target propeller frequency band.
        """
        n_samples = len(audio_signal)
        if n_samples == 0:
            return {"detected": False, "dominant_freq": 0.0, "confidence": 0.0}

        # Apply Hanning window to reduce spectral leakage
        windowed_signal = audio_signal * np.hanning(n_samples)

        # Compute Real FFT and corresponding frequencies
        fft_magnitudes = np.abs(rfft(windowed_signal))
        frequencies = rfftfreq(n_samples, d=1.0 / self.sample_rate)

        # Filter frequencies within the target rotor band
        band_mask = (frequencies >= self.min_freq) & (frequencies <= self.max_freq)
        band_freqs = frequencies[band_mask]
        band_mags = fft_magnitudes[band_mask]

        if len(band_mags) == 0:
            return {"detected": False, "dominant_freq": 0.0, "confidence": 0.0}

        # Find dominant frequency peak in the target band
        peak_idx = np.argmax(band_mags)
        dominant_freq = float(band_freqs[peak_idx])
        peak_magnitude = float(band_mags[peak_idx])

        # Compute Signal-to-Noise Ratio (SNR) within the target band
        noise_floor = float(np.mean(band_mags)) + 1e-9
        snr = peak_magnitude / noise_floor
        confidence = min(snr / 15.0, 1.0)
        is_detected = confidence >= self.energy_threshold

        return {
            "detected": is_detected,
            "dominant_freq": round(dominant_freq, 2),
            "confidence": round(confidence, 2)
        }


