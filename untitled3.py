def add_3d_arrow_label(fig, target_xyz, label_xyz, text_label, arrow_color="#FF5252"):
    """Draws a 3D pointer line, arrowhead cone, and clear text label."""
    tx, ty, tz = target_xyz
    lx, ly, lz = label_xyz

    # Pointer line from label to target component
    fig.add_trace(go.Scatter3d(
        x=(lx, tx), y=(ly, ty), z=(lz, tz),
        mode="lines",
        line=dict(color=arrow_color, width=4),
        showlegend=False
    ))

    # 3D Arrowhead pointing at the component
    dx, dy, dz = tx - lx, ty - ly, tz - lz
    fig.add_trace(go.Cone(
        x=(tx,), y=(ty,), z=(tz,),
        u=(dx,), v=(dy,), w=(dz,),
        sizemode="absolute",
        sizeref=12,
        anchor="tip",
        colorscale=((0, arrow_color), (1, arrow_color)),
        showscale=False,
        showlegend=False
    ))

    # Text annotation at the start of the arrow
    fig.add_trace(go.Scatter3d(
        x=(lx,), y=(ly,), z=(lz + 4,),
        mode="text",
        text=(text_label,),
        textfont=dict(size=12, color="white", family="Arial Black"),
        showlegend=False
    ))


