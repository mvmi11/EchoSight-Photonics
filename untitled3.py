import numpy as np
import matplotlib.pyplot as plt
import matplotlib.patches as patches


class EmbeddedMCUSimulator:
    """
    Simulates the onboard Microcontroller Unit (MCU) hardware interfaces:
    - 12-bit ADC acoustic quantization (0 - 4095 levels)
    - Closed-loop PID to 50Hz Servo PWM pulse-width translation (1000us - 2000us)
    - SPI high-speed camera frame transfer timing
    """

    def __init__(self, adc_bits: int = 12, pwm_freq_hz: float = 50.0, spi_clock_mhz: float = 20.0):
        self.adc_levels = (2 ** adc_bits) - 1
        self.pwm_freq = pwm_freq_hz
        self.pwm_period_ms = 1000.0 / pwm_freq_hz
        self.spi_clock_mhz = spi_clock_mhz

    def simulate_12bit_adc(self, duration_ms: float = 15.0, fs: int = 44100):
        t = np.linspace(0, duration_ms / 1000.0, int(fs * (duration_ms / 1000.0)))
        # Continuous analog mic voltage (0.0V to 3.3V centered at 1.65V)
        analog_v = 1.65 + 0.9 * np.sin(2 * np.pi * 240.0 * t) + 0.25 * np.random.normal(0, 1, len(t))
        analog_v = np.clip(analog_v, 0.0, 3.3)
        # Quantize into 12-bit discrete digital integers (0..4095)
        digital_adc = np.round((analog_v / 3.3) * self.adc_levels).astype(int)
        return t * 1000.0, analog_v, digital_adc

    def angle_to_pwm_us(self, angle_deg: float) -> float:
        """Maps gimbal angle (-45 to +45 deg) to standard servo PWM pulse (1000us to 2000us)."""
        center_us = 1500.0
        us_per_deg = 500.0 / 45.0
        return round(center_us + (angle_deg * us_per_deg), 1)

    def generate_pwm_waveform(self, pulse_us: float, duration_ms: float = 40.0):
        t_ms = np.linspace(0, duration_ms, 2000)
        cycle_pos_ms = np.mod(t_ms, self.pwm_period_ms)
        pulse_ms = pulse_us / 1000.0
        pwm_voltage = np.where(cycle_pos_ms <= pulse_ms, 3.3, 0.0)
        return t_ms, pwm_voltage

    def compute_spi_latency_ms(self, width: int = 480, height: int = 360) -> float:
        total_bits = width * height * 8
        transfer_sec = total_bits / (self.spi_clock_mhz * 1e6)
        return round(transfer_sec * 1000.0, 2)

