def rotate_translate(pts, pos, roll, pitch, yaw):
    x0, y0, z0 = pos
    cr, sr = np.cos(roll), np.sin(roll)
    cp, sp = np.cos(pitch), np.sin(pitch)
    cy, sy = np.cos(yaw), np.sin(yaw)

    Rx = np.array(((1.0, 0.0, 0.0), (0.0, cr, -sr), (0.0, sr, cr)), dtype=float)
    Ry = np.array(((cp, 0.0, sp), (0.0, 1.0, 0.0), (-sp, 0.0, cp)), dtype=float)
    Rz = np.array(((cy, -sy, 0.0), (sy, cy, 0.0), (0.0, 0.0, 1.0)), dtype=float)
    R = Rz @ Ry @ Rx

    arr = np.array(pts, dtype=float)
    return ((arr @ R.T) + np.array((x0, y0, z0))).tolist()


def build_drone_mesh(pos, roll, pitch, yaw, rotor_angle, scale=1.0):
    """Builds 3D geometry for an X-Frame Quadcopter with rotors and bottom sensor pod."""
    s = scale
    hub_top = rotate_translate([(-3.2*s, -4.0*s, 1.0*s), (3.2*s, -4.0*s, 1.0*s), (3.2*s, 4.0*s, 1.0*s), (-3.2*s, 4.0*s, 1.0*s)], pos, roll, pitch, yaw)
    hub_bot = rotate_translate([(-3.2*s, -4.0*s, -1.0*s), (3.2*s, -4.0*s, -1.0*s), (3.2*s, 4.0*s, -1.0*s), (-3.2*s, 4.0*s, -1.0*s)], pos, roll, pitch, yaw)

    arm_tips = ((11.0*s, 11.0*s, 0.7*s), (-11.0*s, 11.0*s, 0.7*s), (-11.0*s, -11.0*s, 0.7*s), (11.0*s, -11.0*s, 0.7*s))
    arms, rotors = [], []
    for idx, (ax_l, ay_l, az_l) in enumerate(arm_tips):
        p0 = rotate_translate([(0.0, 0.0, 0.3*s)], pos, roll, pitch, yaw).pop()
        p1 = rotate_translate([(ax_l, ay_l, az_l)], pos, roll, pitch, yaw).pop()
        arms.append((p0, p1))

        d = 1.0 if idx % 2 == 0 else -1.0
        ang = rotor_angle * d + (idx * np.pi / 4.0)
        bx, by = 6.0 * s * np.cos(ang), 6.0 * s * np.sin(ang)
        r0 = rotate_translate([(ax_l - bx, ay_l - by, az_l + 0.5*s)], pos, roll, pitch, yaw).pop()
        r1 = rotate_translate([(ax_l + bx, ay_l + by, az_l + 0.5*s)], pos, roll, pitch, yaw).pop()
        rotors.append((r0, r1))

    sensor_pt = rotate_translate([(0.0, 3.5*s, -1.8*s)], pos, roll, pitch, yaw).pop()
    tail_pt = rotate_translate([(0.0, -4.2*s, -1.0*s)], pos, roll, pitch, yaw).pop()
    return [hub_top, hub_bot], arms, rotors, sensor_pt, tail_pt


