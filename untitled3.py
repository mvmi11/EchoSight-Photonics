def transform_pts(pts, pos, roll, pitch, yaw):
    """Applies 3D Roll, Pitch, Yaw rotation and translation to local coordinates."""
    x0, y0, z0 = pos
    cr, sr = np.cos(roll), np.sin(roll)
    cp, sp = np.cos(pitch), np.sin(pitch)
    cy, sy = np.cos(yaw), np.sin(yaw)

    Rx = np.array([[1, 0, 0], [0, cr, -sr], [0, sr, cr]])
    Ry = np.array([[cp, 0, sp], [0, 1, 0], [-sp, 0, cp]])
    Rz = np.array([[cy, -sy, 0], [sy, cy, 0], [0, 0, 1]])
    R = Rz @ Ry @ Rx

    arr = np.array(pts, dtype=float)
    rotated = (arr @ R.T) + np.array([x0, y0, z0])
    return rotated.tolist()


def build_quadcopter_geometry(pos, roll, pitch, yaw, rotor_angle):
    """Builds 3D geometry for the X-frame Quadcopter, Landing Skids, 4 Rotors, and 3-Axis Gimbal."""
    # 1. Central Avionics Hub (Top Plate & Bottom Plate)
    hub_top = transform_pts([(-4, -5, 1.5), (4, -5, 1.5), (4, 5, 1.5), (-4, 5, 1.5)], pos, roll, pitch, yaw)
    hub_bot = transform_pts([(-4, -5, -1.5), (4, -5, -1.5), (4, 5, -1.5), (-4, 5, -1.5)], pos, roll, pitch, yaw)

    # 2. Four X-Frame Arms & Spinning Rotor Blades
    arm_tips_local = [(14, 14, 1.0), (-14, 14, 1.0), (-14, -14, 1.0), (14, -14, 1.0)]
    arms = []
    rotors = []
    for idx, (ax_l, ay_l, az_l) in enumerate(arm_tips_local):
        p_start = transform_pts([(0, 0, 0.5)], pos, roll, pitch, yaw).pop()
        p_end = transform_pts([(ax_l, ay_l, az_l)], pos, roll, pitch, yaw).pop()
        arms.append((p_start, p_end))

        # Spinning blade line at each motor tip
        direction = 1.0 if idx % 2 == 0 else -1.0
        ang = rotor_angle * direction + (idx * np.pi / 4.0)
        bx = 7.5 * np.cos(ang)
        by = 7.5 * np.sin(ang)
        b1 = transform_pts([(ax_l - bx, ay_l - by, az_l + 0.8)], pos, roll, pitch, yaw).pop()
        b2 = transform_pts([(ax_l + bx, ay_l + by, az_l + 0.8)], pos, roll, pitch, yaw).pop()
        rotors.append((b1, b2))

    # 3. Tall Landing Gear Skids (Matching Bottom Reference Image)
    skids = []
    for side in (-6.5, 6.5):
        strut_f = transform_pts([(side * 0.6, 4.0, -1.5), (side, 5.5, -9.5)], pos, roll, pitch, yaw)
        strut_b = transform_pts([(side * 0.6, -4.0, -1.5), (side, -5.5, -9.5)], pos, roll, pitch, yaw)
        rail = transform_pts([(side, -10.0, -9.5), (side, 10.0, -9.5)], pos, roll, pitch, yaw)
        skids.extend([strut_f, strut_b, rail])

    # 4. Suspended 3-Axis Stabilized Gimbal Camera (Stabilized horizontal despite drone tilt!)
    gimbal_center = transform_pts([(0.0, 2.5, -4.8)], pos, roll, pitch, yaw).pop()
    cam_box = transform_pts([
        (-2.8, 0.5, -6.5), (2.8, 0.5, -6.5), (2.8, 4.5, -6.5), (-2.8, 4.5, -6.5)
    ], pos, roll * 0.15, pitch * 0.15, yaw)

    fiber_spool_pt = transform_pts([(0.0, -5.0, -1.5)], pos, roll, pitch, yaw).pop()
    return [hub_top, hub_bot], [cam_box], arms, rotors, skids, gimbal_center, fiber_spool_pt


