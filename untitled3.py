        pan_pwm_us = self.angle_to_pwm_us(pan_deg)
        tilt_pwm_us = self.angle_to_pwm_us(tilt_deg)
        spi_ms = self.compute_spi_latency_ms()

        t_pwm, pan_wave = self.generate_pwm_waveform(pan_pwm_us)
        _, tilt_wave = self.generate_pwm_waveform(tilt_pwm_us)

        fig = plt.figure(figsize=(15, 9), dpi=200, facecolor="#0F172A")
        gs = fig.add_gridspec(2, 2, height_ratios=[1.1, 1.0])
