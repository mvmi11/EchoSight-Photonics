import plotly.graph_objects as go


def create_trace(mesh: trimesh.Trimesh, name: str, color: str, opacity: float = 1.0):
    x, y, z = mesh.vertices.T
    i, j, k = mesh.faces.T
    return go.Mesh3d(
        x=x, y=y, z=z, i=i, j=j, k=k,
        name=name, color=color, opacity=opacity,
        flatshading=False,
        lighting=dict(ambient=0.5, diffuse=0.8, roughness=0.3, specular=0.5)
    )


def build_3d_flying_wing_uav():
    traces = []
    solid_parts = []

    # 1. Center Fuselage & Swept Wings (Semi-Transparent Aerodynamic Shell)
    # Center body
    fuselage = trimesh.creation.box(extents=(70.0, 140.0, 18.0))
    fuselage.apply_translation((0.0, 0.0, 10.0))
    traces.append(create_trace(fuselage, "Center Fuselage (Shell)", "#CFD8DC", opacity=0.35))
    solid_parts.append(fuselage)

    # Left & Right Swept Wings
    for side in (-1.0, 1.0):
        wing = trimesh.creation.box(extents=(160.0, 65.0, 8.0))
        sweep = trimesh.transformations.rotation_matrix(np.radians(side * -22.0), (0.0, 0.0, 1.0))
        dihedral = trimesh.transformations.rotation_matrix(np.radians(side * 4.0), (0.0, 1.0, 0.0))
        wing.apply_transform(sweep @ dihedral)
        wing.apply_translation((side * 105.0, -22.0, 11.0))
        traces.append(create_trace(wing, f"{'Right' if side > 0 else 'Left'} Swept Wing", "#B0BEC5", opacity=0.45))
        solid_parts.append(wing)

        # Vertical Stabilizer Fins (under/over wing)
        fin = trimesh.creation.box(extents=(3.0, 35.0, 22.0))
        fin.apply_translation((side * 42.0, -52.0, 6.0))
        traces.append(create_trace(fin, "Vertical Stabilizer", "#455A64", opacity=0.9))
        solid_parts.append(fin)

    # 2. Front Puller Brushless Motor & Propeller (+Y Nose)
    rot_x = trimesh.transformations.rotation_matrix(np.pi / 2.0, (1.0, 0.0, 0.0))
    motor_bell = trimesh.creation.cylinder(radius=11.0, height=18.0, sections=36)
    motor_bell.apply_transform(rot_x)
    motor_bell.apply_translation((0.0, 78.0, 12.0))
    traces.append(create_trace(motor_bell, "Outrunner Brushless Motor", "#D4AF37", opacity=1.0))
    solid_parts.append(motor_bell)

    propeller = trimesh.creation.box(extents=(95.0, 3.0, 8.0))
    propeller.apply_translation((0.0, 89.0, 12.0))
    traces.append(create_trace(propeller, "Puller Propeller", "#212121", opacity=1.0))
    solid_parts.append(propeller)

    # 3. Bottom EO/IR Gimbal Camera Ball (Underbelly)
    gimbal_ball = trimesh.creation.icosphere(subdivisions=3, radius=18.0)
    gimbal_ball.apply_translation((0.0, 15.0, -8.0))
    traces.append(create_trace(gimbal_ball, "EO/IR Gimbal Turret", "#263238", opacity=0.85))
    solid_parts.append(gimbal_ball)

    cam_lens = trimesh.creation.cylinder(radius=7.0, height=10.0, sections=32)
    cam_lens.apply_transform(rot_x)
    cam_lens.apply_translation((0.0, 31.0, -8.0))
    traces.append(create_trace(cam_lens, "Optical Camera Lens", "#00BCD4", opacity=1.0))
    solid_parts.append(cam_lens)

    # 4. Internal Electronics (Visible Through the Transparent Shell!)
    # A. Flight Controller & Optical PCB (Green)
    pcb = trimesh.creation.box(extents=(44.0, 65.0, 3.0))
    pcb.apply_translation((0.0, 10.0, 12.0))
    traces.append(create_trace(pcb, "OpticDroneUnit PCB", "#2E7D32", opacity=1.0))
    solid_parts.append(pcb)

    # B. 4S Li-Po Battery Pack (Blue)
    battery = trimesh.creation.box(extents=(38.0, 45.0, 10.0))
    battery.apply_translation((0.0, 35.0, 11.0))
    traces.append(create_trace(battery, "4S Li-Po Battery", "#1565C0", opacity=1.0))
    solid_parts.append(battery)

    # C. SFP Optical Transceiver & Rear Fiber Spool (Silver & Yellow)
    sfp = trimesh.creation.box(extents=(14.0, 22.0, 8.0))
    sfp.apply_translation((0.0, -28.0, 12.0))
    traces.append(create_trace(sfp, "SFP Optical Module", "#90A4AE", opacity=1.0))
    solid_parts.append(sfp)

    spool = trimesh.creation.cylinder(radius=16.0, height=24.0, sections=36)
    spool.apply_transform(rot_x)
    spool.apply_translation((0.0, -52.0, 11.0))
    traces.append(create_trace(spool, "G.657.A2 Fiber Spool", "#FBC02D", opacity=1.0))
    solid_parts.append(spool)

    # Export printable STL
