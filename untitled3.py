def get_wing_polygons(pos, yaw_rad, prop_angle):
    """Generates rotated 3D polygons for the blended flying-wing UAV, gimbal ball, spool, and propeller."""
    x0, y0, z0 = pos
    c, s = np.cos(yaw_rad), np.sin(yaw_rad)

    def rot(pts):
        res = []
        for px, py, pz in pts:
            rx = x0 + (px * c - py * s)
            ry = y0 + (px * s + py * c)
            rz = z0 + pz
            res.append((rx, ry, rz))
        return res

    # Main Swept Flying-Wing Body
    wing_top = rot([
        (0.0, 18.0, 1.5), (6.0, 12.0, 1.5), (38.0, -7.0, 0.8), (38.0, -13.0, 0.5),
        (10.0, -11.0, 1.2), (0.0, -14.0, 1.5), (-10.0, -11.0, 1.2), (-38.0, -13.0, 0.5),
        (-38.0, -7.0, 0.8), (-6.0, 12.0, 1.5)
    ])

    # Vertical Stabilizer Fins
    fin_r = rot([(10.0, -6.0, 0.0), (10.0, -13.0, 0.0), (10.0, -13.0, -5.0), (10.0, -8.0, -5.0)])
    fin_l = rot([(-10.0, -6.0, 0.0), (-10.0, -13.0, 0.0), (-10.0, -13.0, -5.0), (-10.0, -8.0, -5.0)])

    # Underbelly EO/IR Gimbal Ball (approximated as octahedron/prism)
    gimbal = rot([
        (-3.5, 4.0, -2.5), (3.5, 4.0, -2.5), (3.5, 9.0, -2.5), (-3.5, 9.0, -2.5)
    ])

    # Rear G.657.A2 Yellow Fiber-Optic Spool
    spool = rot([
        (-3.0, -11.0, 1.8), (3.0, -11.0, 1.8), (3.0, -15.0, 1.8), (-3.0, -15.0, 1.8)
    ])

    # Spinning Puller Propeller Blades at Nose
    p_len = 14.0 * np.cos(prop_angle)
    p_z = 5.0 * np.sin(prop_angle)
    prop_pts = rot([(-p_len, 20.0, 1.0 - p_z), (p_len, 20.0, 1.0 + p_z)])

    tail_pt = rot([(0.0, -14.0, 1.0)])[0]
    gimbal_pt = rot([(0.0, 6.5, -2.0)])[0]
    return [wing_top, fin_r, fin_l], gimbal, spool, prop_pts, tail_pt, gimbal_pt


